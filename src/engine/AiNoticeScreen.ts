import { Input } from "./Input";
import { drawHeading, drawHint, drawPageBackdrop, INK, serif, shadowText } from "../render/menuChrome";
import { shouldShowTouchControls } from "./platform";

/** Opened from the main menu's "About AI use" link: how AI was used to make the game. */
const NOTICE_LINES = [
    "The story, the clues and the ideas behind the game are mine,",
    "and I guided every step of the game's direction.",
    "",
    "AI assistants wrote most of the code, including the code that",
    "draws the pixel art and creates the sound, while I directed",
    "the look and feel at every step. AI also wrote individual",
    "lines of dialog, which I reviewed and edited.",
    "Nothing in the game is generated by AI while you play.",
    "",
    "I have great respect for artists of every kind, from",
    "illustrators to musicians. But without AI tools this project",
    "would have taken me ten years. It's a fun project, so if",
    "that's a problem for you, bugger off."
];

export class AiNoticeScreen {
    constructor(
        private input: Input,
        private onComplete: () => void
    ) {}

    update(): void {
        const close =
            this.input.wasPressed(" ") ||
            this.input.wasPressed("enter") ||
            this.input.wasPressed("e") ||
            this.input.wasPressed("escape");
        if (close) this.onComplete();
    }

    render(ctx: CanvasRenderingContext2D): void {
        const w = ctx.canvas.width;
        const h = ctx.canvas.height;
        const scale = h / 600;
        const t = performance.now() / 1000;
        const cx = w / 2;

        drawPageBackdrop(ctx, w, h, t);
        ctx.textAlign = "center";
        drawHeading(ctx, "A Note on AI", cx, h * 0.14, scale);

        const lineHeight = 26 * scale;
        let y = h * 0.27;
        ctx.font = serif(19 * scale);
        for (const line of NOTICE_LINES) {
            if (line) shadowText(ctx, line, cx, y, INK, 2);
            y += line ? lineHeight : lineHeight * 0.6;
        }

        const hint = shouldShowTouchControls() ? "Tap to return" : "Press Enter or Esc to return";
        drawHint(ctx, hint, cx, h * 0.9, scale, t);
        ctx.textAlign = "left";
    }
}
